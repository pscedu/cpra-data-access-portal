const types = {
  hydro_compartment: { type: "hydro_compartment", parentType: "ecoregion" },
  ecoregion: {
    type: "ecoregion",
    parentType: "region",
    childType: "hydro_compartment",
    childIds: ecoregions,
    names: ecoregionNames,
  },
  region: { type: "region", childType: "ecoregion", childIds: regions },
};

function findParent(childId, { type, childIds, names = {} }) {
  for (let id of Object.keys(childIds)) {
    if (childIds[id].includes(childId)) {
      return {
        type,
        id,
        name: names[id] || id,
        childIds: childIds[id],
      };
    }
  }
}

function getIds(ids, parentType, selectedType) {
  while (parentType.childType !== selectedType.type) {
    let childType = types[parentType.childType];
    let childIds = [];
    ids.forEach((id) => childIds.push(...childType.childIds[id]));
    parentType = childType;
    ids = childIds;
  }
  return ids;
}

export function getParentGeographies(feature) {
  const parents = [];
  const selectedType = types[feature.sourceLayer];
  if (!selectedType) return parents;
  const childIds = { [selectedType.type]: feature.id };

  let currentType = selectedType;
  while (currentType.parentType) {
    let parentType = types[currentType.parentType];
    let parent = findParent(childIds[currentType.type], parentType);
    if (!parent) break;
    childIds[parentType.type] = parent.id;
    parent.childIds = getIds(parent.childIds, parentType, selectedType);
    parents.push(parent);
    currentType = parentType;
  }

  return parents;
}
